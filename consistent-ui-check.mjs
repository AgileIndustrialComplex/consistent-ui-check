#!/usr/bin/env node
/**
 * consistent-ui-check.mjs — Deterministic UI-consistency harness for a
 * Next.js/Tailwind CRM frontend.
 *
 * It answers a single question for every component file:
 *   "Is this component consistent with the app's canonical design vocabulary?"
 *
 * Deterministic meaning: same source tree -> identical verdict. No LLM, no
 * screenshots, no thresholds — only exact regex/path rules. CI-able: exits
 * non-zero when any component is inconsistent, and can emit a JSON report.
 *
 * Usage:
 *   node consistent-ui-check.mjs [srcDir] [--json] [--json-out FILE]
 *
 * Rules (each is exact and self-describing):
 *   RAW_HEX        A color hex literal not present in the token allowlist.
 *   BUTTON_SHELL  A raw <button> in a file that does NOT import the shared
 *                  Button  -> component bypasses the canonical primitive.
 *   MODAL_SHELL   A direct <Dialog> / <DialogPanel> (Headless UI) in a file
 *                  that does NOT import the shared Modal -> bypasses the
 *                  canonical shell.
 *   CN_ORIGIN     The file imports `cn` from a non-canonical path.
 *   MAGIC_VALUE   A spacing/radius/typography utility class that the app has
 *                  tokenized elsewhere and should not be hardcoded.
 *
 * A file is CONSISTENT only when no applicable rule fails for it.
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

// ---------------------------------------------------------------------------
// Configuration — the single source of truth for "what is canonical".
// ---------------------------------------------------------------------------
const CONFIG = {
  // Canonical shared components (import specifiers as they appear in the code).
  sharedButton: /(?:Buttons\/Button|Buttons'|Button')/, // path fragment for shared Button
  sharedModal: /modals\/Modal/,
  // Canonical path(s) `cn` may be imported from. Everything else is a violation.
  canonicalCn: [/@\/?utils\/cn/, /@\/?lib\/cn/],
  // Color hexes that ARE allowed because they're the app's design tokens.
  // (Extension point: move real palette here, then every hex NOT listed is a
  //  hardcoded inconsistency automatically.)
  colorTokens: new Set([
    '#ffffff', '#171717', '#ededed', // globals.css root vars
    '#000000',
  ]),
  // Raw hex that is known-OK elsewhere (e.g. inline SVG fills). Extend as
  // legitimately-token exceptions are found and THEN promoted to colorTokens.
  hexIgnorePattern: new RegExp('^$'), // deliberately matches nothing for now
  // Header comment or legacy fence: files matching any of these are skipped.
  ignoreHeaders: [/generated by/i],
  // Canonical primitive files that DEFINE the tokens the rules police.
  // They are the source of truth, not violations — exempt them so the harness
  // doesn't flag the design system itself.
  canonicalSources: [
    /components\/Buttons\/Button\.tsx$/,
    /components\/modals\/Modal\.tsx$/,
    /utils\/cn\.ts$/,
    /lib\/utils\.ts$/,
  ],
};

// Utility classes that must come from a token/primitive, not re-invented.
// Each maps to the canonical token class it should be replaced by.
const MAGIC_VALUES = [
  { re: /rounded-md/, canonical: 'rounded-md (shared Button/Modal radius)' },
  { re: /rounded-lg/, canonical: 'rounded-lg (shared Modal radius)' },
  { re: /\bh-8\b/, canonical: 'h-8 (shared Button height)' },
  { re: /\bpx-3\b/, canonical: 'px-3 (shared Button padding)' },
  { re: /\btext-sm\b/, canonical: 'text-sm (shared Button/typography)' },
];

// ---------------------------------------------------------------------------
// Fetching the canonical allowlist from CONFIG for reuse below.
const colorRe = /#[0-9a-fA-F]{6}\b/g;

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    const st = statSync(p);
    if (st.isDirectory()) {
      if (['node_modules', '.next', '.git', 'dist', 'build'].includes(name)) continue;
      walk(p, out);
    } else if (/\.(tsx|jsx)$/.test(name) && !/\.(test|spec)\./.test(name)) {
      out.push(p);
    }
  }
  return out;
}

function analyze(srcDir) {
  const files = walk(srcDir);
  const report = { meta: { srcDir, rules: Object.keys(ruleDefs), filesScanned: files.length }, files: [] };
  for (const file of files) {
    const raw = readFileSync(file, 'utf8');
    const rel = resolve(file).replace(resolve(srcDir) + '/', '');
    const verdict = verdictFor(raw, rel, file);
    report.files.push(verdict);
  }
  const inconsistent = report.files.filter((f) => f.status !== 'CONSISTENT' && f.status !== 'SKIPPED');
  return { report, inconsistent, total: files.length };
}

const ruleDefs = {
  RAW_HEX: 'color hex literal not in token allowlist',
  BUTTON_SHELL: 'raw <button> without importing shared Button',
  MODAL_SHELL: 'direct <Dialog> without importing shared Modal',
  CN_ORIGIN: 'cn imported from a non-canonical path',
  MAGIC_VALUE: 'tokenized utility class hardcoded',
};

function verdictFor(code, rel, absPath) {
  // legacy/skip fence -------------------------------------------------------
  for (const h of CONFIG.ignoreHeaders) if (h.test(code)) return { file: rel, path: absPath, status: 'SKIPPED', violations: [] };
  // canonical design-system sources are the reference, not subjects ---------
  if (CONFIG.canonicalSources.some((re) => re.test(rel)))
    return { file: rel, path: absPath, status: 'CANONICAL', violations: [] };

  const v = { file: rel, path: absPath, status: 'CONSISTENT', violations: [] };
  const hasHex = (m) => !!m;
  const hexMatches = [...code.matchAll(colorRe)]
    .map((m) => m[0].toLowerCase())
    .filter((h, i, a) => a.indexOf(h) === i);

  const importsSharedButton = CONFIG.sharedButton.test(code);
  const hasRawButton = /<button\b/.test(code);
  const importsSharedModal = CONFIG.sharedModal.test(code);
  const hasDirectDialog = /<Dialog\b|<DialogPanel\b/.test(code);

  // cn import origin
  const cnImports = [...code.matchAll(/import\s*\{[^}]*\bcn\b[^}]*\}\s*from\s*['"]([^'"]+)['"]/g)]
    .map((m) => m[1]);

  const push = (rule, detail) => v.violations.push({ rule, detail });

  // 1. RAW_HEX ---------------------------------------------------------------
  for (const h of hexMatches) {
    if (CONFIG.colorTokens.has(h)) continue;
    if (CONFIG.hexIgnorePattern.test(h)) continue;
    push('RAW_HEX', `hardcoded color ${h} — promote to a token in tailwind.config/colorTokens`);
  }

  // 2. BUTTON_SHELL -----------------------------------------------------------
  if (hasRawButton && !importsSharedButton) {
    push('BUTTON_SHELL', 'renders a raw <button> but does not import the shared Button component');
  }

  // 3. MODAL_SHELL -------------------------------------------------------------
  if (hasDirectDialog && !importsSharedModal) {
    push('MODAL_SHELL', 'uses Headless UI <Dialog> directly but does not import the shared Modal shell');
  }

  // 4. CN_ORIGIN ---------------------------------------------------------------
  const badCn = cnImports.filter((p) => !CONFIG.canonicalCn.some((re) => re.test(p)));
  for (const p of badCn) push('CN_ORIGIN', `cn imported from non-canonical path '${p}'`);

  // 5. MAGIC_VALUE --------------------------------------------------------------
  for (const mv of MAGIC_VALUES) {
    if (mv.re.test(code)) push('MAGIC_VALUE', `hardcoded '${mv.canonical.split(' (' )[0]}' — should come from shared primitive (${mv.canonical})`);
  }

  if (v.violations.length) v.status = 'INCONSISTENT';
  return v;
}

// ---------------------------------------------------------------------------
const args = process.argv.slice(2);
let srcDir = args.find((a) => !a.startsWith('--')) || 'src';
srcDir = resolve(srcDir);
const wantJson = args.includes('--json');
const jsonOutIdx = args.indexOf('--json-out');
const jsonOut = jsonOutIdx >= 0 ? args[jsonOutIdx + 1] : null;

const { report, inconsistent, total } = analyze(srcDir);

// plain human summary
if (!wantJson && !jsonOut) {
  console.log(`\nConsistent-UI harness — scan of ${srcDir}`);
  console.log(`  files scanned : ${total}`);
  console.log(`  canonical src : ${report.files.filter((f) => f.status === 'CANONICAL').length}`);
  console.log(`  consistent    : ${report.files.filter((f) => f.status === 'CONSISTENT').length}`);
  console.log(`  skipped       : ${report.files.filter((f) => f.status === 'SKIPPED').length}`);
  console.log(`  INCONSISTENT  : ${inconsistent.length}\n`);
  // rule totals
  const ruleCounts = {};
  for (const f of report.files) for (const vn of f.violations) ruleCounts[vn.rule] = (ruleCounts[vn.rule] || 0) + 1;
  console.log('violations by rule:');
  for (const [r, c] of Object.entries(ruleCounts).sort((a, b) => b[1] - a[1]))
    console.log(`  ${r.padEnd(14)} ${String(c).padStart(4)}`);
  console.log('\nmost inconsistent files:');
  const top = [...inconsistent].sort((a, b) => b.violations.length - a.violations.length).slice(0, 15);
  for (const f of top)
    console.log(`  ${f.file}  (${f.violations.map((v) => v.rule).join(', ')})`);
  console.log('');
}

if (jsonOut) writeFileSync(jsonOut, JSON.stringify(report, null, 2));
if (wantJson) console.log(JSON.stringify(report, null, 2));

// CI gate
process.exit(inconsistent.length ? 1 : 0);